#!/usr/bin/env python3
"""LOCO column imputation with an already trained TabSyn model.

This adapts TabSyn's target-only ``impute.py`` to arbitrary numerical and
categorical columns. Known columns are re-noised and clamped at every reverse
diffusion step; masked latent tokens are generated by the unconditional model.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd


SIGMA_MIN = 0.002
SIGMA_MAX = 80.0
RHO = 7.0
S_CHURN = 1.0
S_MIN = 0.0
S_MAX = float("inf")
S_NOISE = 1.0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Impute arbitrary columns with a trained TabSyn model."
    )
    parser.add_argument("--dataname", required=True)
    parser.add_argument("--tabsyn-repo", type=Path, default=Path("external/tabsyn"))
    parser.add_argument("--mask-cols", nargs="+", required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--trials", type=int, default=10)
    parser.add_argument("--batch-size", type=int, default=2048)
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument(
        "--resample-rounds",
        type=int,
        default=1,
        help="RePaint rounds per diffusion step. Upstream TabSyn uses 20.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--split", choices=["train", "test"], default="test")
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--limit", type=int)
    return parser.parse_args()


def configure_imports(repo: Path) -> None:
    repo = repo.resolve()
    if not (repo / "tabsyn" / "model.py").exists():
        raise FileNotFoundError(f"TabSyn source is missing under {repo}")
    sys.path.insert(0, str(repo))


def load_state(path: Path, device: Any) -> Any:
    import torch

    if not path.exists():
        raise FileNotFoundError(f"Checkpoint is missing: {path}")
    try:
        return torch.load(path, map_location=device, weights_only=True)
    except TypeError:
        return torch.load(path, map_location=device)


def column_token_mapping(info: dict[str, Any]) -> dict[str, tuple[str, int, int]]:
    """Map name to (kind, transformed-column index, latent-token index)."""
    names = {
        int(index): str(name) for index, name in info["idx_name_mapping"].items()
    }
    targets = list(info["target_col_idx"])
    numerical = list(info["num_col_idx"])
    categorical = list(info["cat_col_idx"])

    if info["task_type"] == "regression":
        num_original = targets + numerical
        cat_original = categorical
    else:
        num_original = numerical
        cat_original = targets + categorical

    mapping: dict[str, tuple[str, int, int]] = {}
    for transformed_index, original_index in enumerate(num_original):
        mapping[names[original_index]] = ("numerical", transformed_index, transformed_index)
    for transformed_index, original_index in enumerate(cat_original):
        mapping[names[original_index]] = (
            "categorical",
            transformed_index,
            len(num_original) + transformed_index,
        )
    return mapping


def select_model_columns(frame: pd.DataFrame, info: dict[str, Any]) -> pd.DataFrame:
    """Project a prepared table onto the columns represented by the checkpoint."""
    names = {
        int(index): str(name) for index, name in info["idx_name_mapping"].items()
    }
    modeled_indices = sorted(
        {
            *map(int, info["target_col_idx"]),
            *map(int, info["num_col_idx"]),
            *map(int, info["cat_col_idx"]),
        }
    )
    missing_names = [index for index in modeled_indices if index not in names]
    if missing_names:
        raise ValueError(f"Missing idx_name_mapping entries: {missing_names}")

    expected = [names[index] for index in modeled_indices]
    missing_columns = [column for column in expected if column not in frame.columns]
    if missing_columns:
        raise ValueError(
            f"Prepared test data is missing model columns: {missing_columns}. "
            f"Available: {list(frame.columns)}"
        )
    return frame.loc[:, expected].copy()


def mask_transformed_data(
    train_num: np.ndarray,
    test_num: np.ndarray,
    train_cat: np.ndarray,
    test_cat: np.ndarray,
    mapping: dict[str, tuple[str, int, int]],
    mask_cols: list[str],
) -> tuple[np.ndarray, np.ndarray, list[int]]:
    test_num = test_num.copy()
    test_cat = test_cat.copy()
    latent_tokens: list[int] = []
    for column in mask_cols:
        kind, transformed_index, token_index = mapping[column]
        latent_tokens.append(token_index)
        if kind == "numerical":
            test_num[:, transformed_index] = np.nanmean(train_num[:, transformed_index])
        else:
            values, counts = np.unique(train_cat[:, transformed_index], return_counts=True)
            test_cat[:, transformed_index] = values[np.argmax(counts)]
    return test_num, test_cat, sorted(set(latent_tokens))


def encode_condition(
    encoder: Any,
    test_num: np.ndarray,
    test_cat: np.ndarray,
    mean: Any,
    batch_size: int,
    device: Any,
) -> Any:
    import torch

    parts = []
    encoder.eval()
    with torch.no_grad():
        for start in range(0, len(test_num), batch_size):
            x_num = torch.as_tensor(
                test_num[start : start + batch_size], dtype=torch.float32, device=device
            )
            x_cat = torch.as_tensor(
                test_cat[start : start + batch_size], dtype=torch.long, device=device
            )
            latent = encoder(x_num, x_cat)[:, 1:, :].flatten(1)
            parts.append(((latent - mean) / 2.0).cpu())
    return torch.cat(parts, dim=0)


def denoise_step(net: Any, num_steps: int, index: int, t_cur: Any, t_next: Any, x_cur: Any) -> Any:
    import torch

    gamma = (
        min(S_CHURN / num_steps, np.sqrt(2.0) - 1.0)
        if S_MIN <= float(t_cur) <= S_MAX
        else 0.0
    )
    t_hat = net.round_sigma(t_cur + gamma * t_cur)
    x_hat = x_cur + (t_hat.square() - t_cur.square()).clamp_min(0).sqrt() * S_NOISE * torch.randn_like(x_cur)
    denoised = net(x_hat, t_hat).to(torch.float32)
    derivative = (x_hat - denoised) / t_hat
    x_next = x_hat + (t_next - t_hat) * derivative

    if index < num_steps - 1:
        denoised_next = net(x_next, t_next).to(torch.float32)
        derivative_next = (x_next - denoised_next) / t_next
        x_next = x_hat + (t_next - t_hat) * (0.5 * derivative + 0.5 * derivative_next)
    return x_next


def make_schedule(net: Any, steps: int, device: Any) -> Any:
    import torch

    indices = torch.arange(steps, dtype=torch.float32, device=device)
    sigma_min = max(SIGMA_MIN, net.sigma_min)
    sigma_max = min(SIGMA_MAX, net.sigma_max)
    schedule = (
        sigma_max ** (1 / RHO)
        + indices / (steps - 1) * (sigma_min ** (1 / RHO) - sigma_max ** (1 / RHO))
    ) ** RHO
    return torch.cat([net.round_sigma(schedule), torch.zeros_like(schedule[:1])])


def sample_latent_batch(
    net: Any,
    condition: Any,
    flat_mask: Any,
    schedule: Any,
    resample_rounds: int,
) -> Any:
    import torch

    x_t = torch.randn_like(condition) * schedule[0]
    mask = flat_mask.to(device=condition.device, dtype=condition.dtype).unsqueeze(0)
    steps = len(schedule) - 1

    with torch.no_grad():
        for index, (t_cur, t_next) in enumerate(zip(schedule[:-1], schedule[1:])):
            for round_index in range(resample_rounds):
                known_previous = condition + torch.randn_like(condition) * t_next
                unknown_previous = denoise_step(
                    net, steps, index, t_cur, t_next, x_t
                )
                previous = known_previous * (1.0 - mask) + unknown_previous * mask
                if round_index + 1 == resample_rounds:
                    x_t = previous
                else:
                    noise_scale = (t_cur.square() - t_next.square()).clamp_min(0).sqrt()
                    x_t = previous + torch.randn_like(previous) * noise_scale
    return x_t


def decode_latent(
    latent: Any,
    decoder: Any,
    token_dim: int,
    num_inverse: Any,
    cat_inverse: Any,
    info: dict[str, Any],
    device: Any,
) -> pd.DataFrame:
    import torch
    from tabsyn.latent_utils import recover_data

    decoder.eval()
    with torch.no_grad():
        decoded_num, decoded_cat_logits = decoder(latent.reshape(len(latent), -1, token_dim))
    decoded_num_np = num_inverse(decoded_num.cpu().numpy())
    if decoded_cat_logits:
        decoded_cat_idx = torch.stack(
            [logits.argmax(dim=-1) for logits in decoded_cat_logits], dim=1
        ).cpu().numpy()
        decoded_cat_np = cat_inverse(decoded_cat_idx)
    else:
        decoded_cat_np = np.empty((len(latent), 0), dtype=object)

    target_count = len(info["target_col_idx"])
    if info["task_type"] == "regression":
        target = decoded_num_np[:, :target_count]
        numerical = decoded_num_np[:, target_count:]
        categorical = decoded_cat_np
    else:
        target = decoded_cat_np[:, :target_count]
        numerical = decoded_num_np
        categorical = decoded_cat_np[:, target_count:]

    frame = recover_data(numerical, categorical, target, info)
    names = {
        int(index): str(name) for index, name in info["idx_name_mapping"].items()
    }
    return frame.rename(columns=names)


def point_estimate(
    real: pd.DataFrame, samples: list[pd.DataFrame], mask_cols: list[str]
) -> pd.DataFrame:
    estimate = real.copy()
    for column in mask_cols:
        values = pd.concat([sample[column] for sample in samples], axis=1)
        if pd.api.types.is_numeric_dtype(real[column]):
            estimate[column] = values.apply(pd.to_numeric, errors="coerce").mean(axis=1)
        else:
            estimate[column] = values.mode(axis=1, dropna=False).iloc[:, 0]
    return estimate


def evaluate(real: pd.DataFrame, estimate: pd.DataFrame, mask_cols: list[str]) -> dict[str, dict[str, float]]:
    from sklearn.metrics import (
        accuracy_score,
        f1_score,
        mean_absolute_error,
        mean_squared_error,
        r2_score,
        recall_score,
    )

    result: dict[str, dict[str, float]] = {}
    for column in mask_cols:
        truth = real[column]
        prediction = estimate[column]
        if pd.api.types.is_numeric_dtype(truth):
            result[column] = {
                "r2": float(r2_score(truth, prediction)),
                "rmse": float(mean_squared_error(truth, prediction) ** 0.5),
                "mae": float(mean_absolute_error(truth, prediction)),
            }
        else:
            result[column] = {
                "accuracy": float(accuracy_score(truth, prediction)),
                "macro_f1": float(f1_score(truth, prediction, average="macro", zero_division=0)),
                "macro_recall": float(recall_score(truth, prediction, average="macro", zero_division=0)),
            }
    return result


def main() -> None:
    args = parse_args()
    if min(args.trials, args.batch_size, args.resample_rounds) < 1 or args.steps < 2:
        raise ValueError(
            "trials, batch-size, and resample-rounds must be positive; steps must be at least 2"
        )

    repo = args.tabsyn_repo.resolve()
    configure_imports(repo)

    import torch
    from tabsyn.model import MLPDiffusion, Model
    from tabsyn.vae.model import Decoder_model, Encoder_model, Model_VAE
    from utils_train import preprocess

    device = torch.device(
        f"cuda:{args.gpu}" if args.gpu >= 0 and torch.cuda.is_available() else "cpu"
    )
    data_dir = repo / "data" / args.dataname
    info = json.loads((data_dir / "info.json").read_text())
    mapping = column_token_mapping(info)
    unknown = sorted(set(args.mask_cols) - set(mapping))
    if unknown:
        raise ValueError(f"Unknown mask columns: {unknown}. Available: {sorted(mapping)}")

    (train_num, test_num), (train_cat, test_cat), categories, d_numerical, num_inverse, cat_inverse = preprocess(
        str(data_dir), task_type=info["task_type"], inverse=True
    )
    if args.split == "train":
        test_num, test_cat = train_num.copy(), train_cat.copy()
    real_path = data_dir / f"{args.split}.csv"
    raw_real = pd.read_csv(real_path)
    if len(raw_real) != len(test_num) or len(raw_real) != len(test_cat):
        raise ValueError(f"Prepared {args.split} CSV and transformed arrays differ in length.")
    real = select_model_columns(raw_real, info)
    dropped_columns = [column for column in raw_real.columns if column not in real.columns]
    if dropped_columns:
        print(
            "Ignoring prepared test columns absent from the trained TabSyn schema: "
            f"{dropped_columns}",
            flush=True,
        )
    if args.limit is not None:
        real = real.iloc[: args.limit].reset_index(drop=True)
        test_num = test_num[: args.limit]
        test_cat = test_cat[: args.limit]

    test_num, test_cat, masked_tokens = mask_transformed_data(
        train_num, test_num, train_cat, test_cat, mapping, args.mask_cols
    )

    token_dim = 4
    vae = Model_VAE(2, d_numerical, categories, token_dim, n_head=1, factor=32, bias=True).to(device)
    vae_path = repo / "tabsyn" / "vae" / "ckpt" / args.dataname / "model.pt"
    vae.load_state_dict(load_state(vae_path, device))
    encoder = Encoder_model(2, d_numerical, categories, token_dim, 1, 32).to(device)
    decoder = Decoder_model(2, d_numerical, categories, token_dim, 1, 32).to(device)
    encoder.load_weights(vae)
    decoder.load_weights(vae)
    del vae

    train_z_path = repo / "tabsyn" / "vae" / "ckpt" / args.dataname / "train_z.npy"
    train_z = torch.as_tensor(np.load(train_z_path)[:, 1:, :], dtype=torch.float32)
    train_flat = train_z.flatten(1)
    latent_mean = train_flat.mean(dim=0).to(device)
    condition = encode_condition(
        encoder, test_num, test_cat, latent_mean, args.batch_size, device
    )
    del encoder

    input_dim = train_flat.shape[1]
    denoise_fn = MLPDiffusion(input_dim, 1024).to(device)
    diffusion = Model(denoise_fn=denoise_fn, hid_dim=input_dim).to(device)
    diffusion_path = repo / "tabsyn" / "ckpt" / args.dataname / "model.pt"
    diffusion.load_state_dict(load_state(diffusion_path, device))
    diffusion.eval()
    net = diffusion.denoise_fn_D
    schedule = make_schedule(net, args.steps, device)

    token_count = train_z.shape[1]
    token_mask = torch.zeros(token_count, dtype=torch.bool)
    token_mask[masked_tokens] = True
    flat_mask = token_mask.repeat_interleave(token_dim)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    samples: list[pd.DataFrame] = []
    observed = [column for column in real.columns if column not in args.mask_cols]
    for trial in range(args.trials):
        trial_seed = args.seed + trial
        np.random.seed(trial_seed)
        torch.manual_seed(trial_seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed_all(trial_seed)

        decoded_parts = []
        for start in range(0, len(condition), args.batch_size):
            condition_batch = condition[start : start + args.batch_size].to(device)
            latent = sample_latent_batch(
                net, condition_batch, flat_mask, schedule, args.resample_rounds
            )
            latent = latent * 2.0 + latent_mean
            decoded_parts.append(
                decode_latent(
                    latent, decoder, token_dim, num_inverse, cat_inverse, info, device
                )
            )

        sample = pd.concat(decoded_parts, ignore_index=True).loc[:, real.columns]
        sample.loc[:, observed] = real.loc[:, observed].to_numpy()
        sample_path = args.output_dir / f"trial_{trial:03d}.csv"
        sample.to_csv(sample_path, index=False)
        samples.append(sample)
        print(f"Saved conditional sample {trial + 1}/{args.trials}: {sample_path}", flush=True)

    estimate = point_estimate(real, samples, args.mask_cols)
    estimate.to_csv(args.output_dir / "point_estimate.csv", index=False)
    metrics = evaluate(real, estimate, args.mask_cols)
    (args.output_dir / "metrics.json").write_text(json.dumps(metrics, indent=2))
    run_info = {
        "dataname": args.dataname,
        "split": args.split,
        "data_csv": str(real_path),
        "cfg": False,
        "vae_checkpoint": str(vae_path),
        "diffusion_checkpoint": str(diffusion_path),
        "mask_cols": args.mask_cols,
        "masked_latent_tokens": masked_tokens,
        "trials": args.trials,
        "rows": len(real),
        "steps": args.steps,
        "resample_rounds": args.resample_rounds,
        "device": str(device),
        "algorithm": "TabSyn latent RePaint-style conditional inpainting",
    }
    (args.output_dir / "run_info.json").write_text(json.dumps(run_info, indent=2))
    print(json.dumps(metrics, indent=2), flush=True)


if __name__ == "__main__":
    main()
